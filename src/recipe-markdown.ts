import { micromark } from "micromark";
import { gfmTable, gfmTableHtml } from "micromark-extension-gfm-table";
import { maxAiRecipeResponseLength } from "./ai-recipe-limits";

const maxMarkdownTableColumns = 64;
const maxMarkdownTableCells = 1000;
const maxMarkdownHtmlLength = 200_000;

export function recipeMarkdownHtml(markdown: string): string | null {
  if (!markdown.trim() || markdown.length > maxAiRecipeResponseLength) return null;
  try {
    let tableCells = 0;
    let tableColumns = 0;
    const tables = gfmTableHtml();
    const enterTable = tables.enter?.table;
    const enterHeader = tables.enter?.tableHeader;
    const enterRow = tables.enter?.tableRow;
    tables.enter = {
      ...tables.enter,
      table(token) {
        tableColumns = 0;
        return enterTable?.call(this, token);
      },
      tableHeader(token) {
        tableColumns += 1;
        tableCells += 1;
        if (tableColumns > maxMarkdownTableColumns || tableCells > maxMarkdownTableCells) {
          throw new Error("Markdown table exceeds the display budget");
        }
        return enterHeader?.call(this, token);
      },
      tableRow(token) {
        // The header row arrives before its cells, so its count is initially zero.
        // Body rows reserve all columns before GFM pads their missing cells.
        tableCells += tableColumns;
        if (tableCells > maxMarkdownTableCells) {
          throw new Error("Markdown table exceeds the display budget");
        }
        return enterRow?.call(this, token);
      },
    };
    const html = micromark(markdown, {
      allowDangerousHtml: false,
      allowDangerousProtocol: false,
      extensions: [{ disable: { null: ["labelStartImage", "htmlFlow", "htmlText"] } }, gfmTable()],
      htmlExtensions: [tables],
    });
    return html.length <= maxMarkdownHtmlLength ? html : null;
  } catch {
    return null;
  }
}

export function renderRecipeMarkdown(container: HTMLElement, markdown: string): boolean {
  const html = recipeMarkdownHtml(markdown);
  if (html === null) {
    container.replaceChildren();
    return false;
  }
  const template = document.createElement("template");
  // Only HTML generated by the configured parser enters this inert template.
  template.innerHTML = html;
  for (const link of template.content.querySelectorAll("a")) {
    try {
      const url = new URL(link.getAttribute("href") ?? "");
      if (url.protocol !== "https:" && url.protocol !== "http:") throw new Error("Unsafe link");
      link.href = url.href;
      link.target = "_blank";
      link.rel = "noopener noreferrer";
    } catch {
      link.replaceWith(...link.childNodes);
    }
  }
  // The answer belongs under the article's h3; model headings start at h4.
  for (const heading of template.content.querySelectorAll("h1,h2,h3,h4,h5,h6")) {
    const nested = document.createElement(`h${Math.min(Number(heading.tagName[1]) + 3, 6)}`);
    nested.append(...heading.childNodes);
    heading.replaceWith(nested);
  }
  for (const table of template.content.querySelectorAll("table")) {
    const wrapper = document.createElement("div");
    wrapper.className = "ai-answer-table";
    wrapper.tabIndex = 0;
    wrapper.setAttribute("role", "region");
    wrapper.setAttribute("aria-label", "回答の表（横にスクロールできます）");
    table.replaceWith(wrapper);
    wrapper.append(table);
  }
  container.replaceChildren(template.content);
  return true;
}
